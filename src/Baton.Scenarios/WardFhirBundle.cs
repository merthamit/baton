using Baton.Core.Escalation;
using Baton.Fhir;
using Hl7.Fhir.Model;

namespace Baton.Scenarios;

/// <summary>
/// One bed as a FHIR R4 transaction Bundle: the Patient (with a birth date giving the planned age at shift start),
/// the diagnosis as a Condition, and all vital-sign Observations, each written with
/// PUT to its own id so loading the ward again updates the same resources instead of duplicating them.
/// </summary>
public static class WardFhirBundle
{
    public const string BedSystem = "urn:baton:bed";
    public const string TagSystem = "urn:baton:tag";

    /// <summary>Identifier system of Baton's confirmed handover documents (Bundle type document).</summary>
    public const string HandoverSystem = "urn:baton:handover";

    /// <summary>
    /// Baton extension on Patient: the recorded clinical decision to use SpO2 Scale 2 (sub-extensions
    /// authorisedBy and authorisedAt). There is no standard FHIR element for it yet.
    /// </summary>
    public const string Scale2Extension = "https://baton.example/fhir/StructureDefinition/spo2-scale2-decision";

    public const string ConditionCategorySystem = "http://terminology.hl7.org/CodeSystem/condition-category";
    public const string ConditionClinicalSystem = "http://terminology.hl7.org/CodeSystem/condition-clinical";
    public const string ConditionVerificationSystem = "http://terminology.hl7.org/CodeSystem/condition-ver-status";

    /// <summary>
    /// The scenario's escalation chain as FHIR resources, plus the NEWS2 Observation of each call's triggering measurement
    /// (the call Task's focus).
    /// </summary>
    private static IEnumerable<Resource> Escalation(WardBed bed, DateTimeOffset shiftStart)
    {
        var records = ScenarioEscalation.From(bed, shiftStart);
        if (records.Count == 0)
        {
            return [];
        }

        var subject = new ResourceReference($"Patient/{bed.PatientId}");
        var news2 = new Dictionary<string, Observation>(StringComparer.Ordinal);

        ResourceReference? News2At(DateTimeOffset at)
        {
            var measurement = bed.Patient.Measurements.LastOrDefault(m => m.At <= at);
            if (measurement is null)
            {
                return null;
            }

            var id = $"news2-{bed.PatientId}-{measurement.At.ToString("yyyyMMddHHmm", System.Globalization.CultureInfo.InvariantCulture)}";
            if (!news2.ContainsKey(id))
            {
                var options = new ReadOptions(measurement.At, TimeSpan.FromHours(13))
                {
                    SpO2Scale = measurement.Input.SpO2Scale,
                    Scale2Authorisation = measurement.Input.Scale2Authorisation,
                };
                var reading = VitalSignsReader.Read(ScenarioFhirExport.ToObservations(bed, measurement), options);
                var observation = News2ObservationWriter.Create(measurement.Score, reading, subject, measurement.At);
                observation.Id = id;
                news2[id] = observation;
            }

            return new ResourceReference($"Observation/{id}");
        }

        var scores = bed.Patient.Measurements.Select(m => new ScoreMark(m.At, m.Score.Risk)).ToList();
        var chain = EscalationFhir.ToResources(records, bed.PatientId, News2At, scores, turkish: ScenarioTranslations.ToTurkish);
        return [.. news2.Values, .. chain];
    }

    public static Bundle Build(WardBed bed)
    {
        ArgumentNullException.ThrowIfNull(bed);
        var shiftStart = bed.Patient.Measurements[0].At.AddHours(-bed.Patient.Measurements[0].Hour);

        // Synthetic birth date: the planned age at shift start, 100 days past the last birthday.
        var birthDate = DateOnly.FromDateTime(shiftStart.Date).AddYears(-bed.Age).AddDays(-100);

        var patient = new Patient
        {
            Id = bed.PatientId,
            Meta = new Meta { Tag = [new Coding(TagSystem, "synthetic", "Synthetic patient generated by Baton")] },
            Identifier = [new Identifier(BedSystem, bed.Bed)],
            Name = [new HumanName { Text = bed.PatientName }],
            BirthDate = birthDate.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
        };

        var decision = bed.Patient.Card.Scale == Core.News2.SpO2Scale.Scale2
            ? bed.Patient.Events.FirstOrDefault(e => e.Kind == ScenarioEventKind.Scale2Decision)
            : null;
        if (decision is not null)
        {
            var at = ShiftSimulator.AtMinute(shiftStart, decision.Hour);
            patient.Extension.Add(new Extension
            {
                Url = Scale2Extension,
                Extension =
                [
                    new Extension("authorisedBy", new FhirString(decision.Text)),
                    new Extension("authorisedAt", new FhirDateTime(at)),
                ],
            });
        }

        var condition = new Condition
        {
            Id = $"condition-{bed.PatientId}",
            Meta = new Meta { Tag = [new Coding(TagSystem, "synthetic", "Synthetic patient generated by Baton")] },
            ClinicalStatus = new CodeableConcept(ConditionClinicalSystem, "active"),
            VerificationStatus = new CodeableConcept(ConditionVerificationSystem, "confirmed"),
            Category = [new CodeableConcept(ConditionCategorySystem, "encounter-diagnosis")],
            Code = new CodeableConcept { Text = bed.Diagnosis },
            Subject = new ResourceReference($"Patient/{bed.PatientId}"),
        };
        if (ScenarioTranslations.ToTurkish(bed.Diagnosis) is { } diagnosisTr)
        {
            FhirTranslation.Add(condition.Code.TextElement!, "tr", diagnosisTr);
        }

        var resources = new List<Resource> { patient, condition };
        resources.AddRange(bed.Patient.Measurements.SelectMany(m => ScenarioFhirExport.ToObservations(bed, m)));
        resources.AddRange(Escalation(bed, shiftStart));
        resources.AddRange(EscalationFhir.Practitioners);
        resources.Add(EscalationFhir.BatonDevice);

        return new Bundle
        {
            Type = Bundle.BundleType.Transaction,
            Entry = resources.Select(r => new Bundle.EntryComponent
            {
                FullUrl = $"urn:uuid:{Guid.NewGuid()}",
                Resource = r,
                Request = new Bundle.RequestComponent { Method = Bundle.HTTPVerb.PUT, Url = $"{r.TypeName}/{r.Id}" },
            }).ToList(),
        };
    }
}
