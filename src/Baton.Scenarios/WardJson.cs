using System.Text.Json;
using System.Text.Json.Serialization;

namespace Baton.Scenarios;

/// <summary>Serialises a generated ward to JSON for the preview board. Synthetic data only.</summary>
public static class WardJson
{
    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public static string Serialize(IReadOnlyList<WardBed> ward, DateTimeOffset shiftStart, int seed, double treatmentDelayHours)
    {
        ArgumentNullException.ThrowIfNull(ward);

        var document = new
        {
            note = "Synthetic data generated by Baton. Not real patients. Not a medical device.",
            shiftStart,
            seed,
            treatmentDelayHours,
            beds = ward.Select(b => new
            {
                bed = b.Bed,
                patientId = b.PatientId,
                name = b.PatientName,
                age = b.Age,
                diagnosis = b.Diagnosis,
                scenario = new { id = b.Patient.Card.Id, title = b.Patient.Card.Title },
                spo2Scale = b.Patient.Card.Scale,
                measurements = b.Patient.Measurements.Select(m => new
                {
                    hour = m.Hour,
                    at = m.At,
                    vitals = m.Vitals,
                    news2 = new
                    {
                        total = m.Score.Total,
                        risk = m.Score.Risk,
                        response = m.Score.Response,
                        frequency = m.Score.MinimumMonitoringFrequency,
                        subScores = m.Score.SubScores,
                        parametersScoring3 = m.Score.ParametersScoring3,
                    },
                }),
                events = b.Patient.Events.Select(e => new { hour = e.Hour, at = ShiftSimulator.AtMinute(shiftStart, e.Hour), kind = e.Kind, text = e.Text }),
            }),
        };

        return JsonSerializer.Serialize(document, Options);
    }
}
